# align.py: word times for a voice take, from faster-whisper, spelled as the script spells them.
#   python align.py <audio.wav> <script words.txt> <out timing.js> <GLOBAL name> [tail seconds]
# Writes window.<GLOBAL> = { dur, vo, words: [{w, t, e}] } and window.wordT(w, n) (the kit's timing format).
import json, re, sys
from faster_whisper import WhisperModel
audio, txt, out_js, name = sys.argv[1:5]
tail = float(sys.argv[5]) if len(sys.argv) > 5 else 1.6
norm = lambda s: re.sub(r"[^a-z0-9']", '', s.lower())
m = WhisperModel('base.en', device='cpu', compute_type='int8')
segs, info = m.transcribe(audio, language='en', word_timestamps=True)
ws = [w for s in segs for w in s.words]
ref = open(txt, encoding='utf8').read().split()
out, j = [], 0
for w in ref:
    key = norm(w)
    k = j
    # numbers come back as digits ("59." for "fifty-nine."), so a word that cannot match by spelling takes the next recognised word
    while k < len(ws) and k < j + 4 and not norm(ws[k].word).startswith(key[:3]): k += 1
    if k < len(ws) and k < j + 4: a = ws[k]; j = k + 1
    else: a = ws[min(j, len(ws) - 1)]; j += 1
    out.append({'w': w, 't': round(a.start, 3), 'e': round(a.end, 3)})
for i in range(1, len(out)):
    if out[i]['t'] < out[i - 1]['t']: out[i]['t'] = out[i - 1]['e']
dur = round(info.duration + tail, 2)
js = f'/* timing: {audio} on the film clock (faster-whisper word times, script spelling). Generated by align.py. */\n'
js += f'window.{name} = ' + json.dumps({'dur': dur, 'vo': audio.replace('\\', '/').split('/')[-2] + '/' + audio.replace('\\', '/').split('/')[-1], 'words': out}) + ';\n'
js += f'window.wordT = (w, n = 1) => {{ const L = window.{name}.words.filter(x => x.w.toLowerCase().replace(/[^a-z0-9-]/g, "") === w); return (L[n - 1] || L[0]).t; }};\n'
open(out_js, 'w', encoding='utf8').write(js)
print(json.dumps({'asr_words': len(ws), 'script_words': len(ref), 'dur': dur, 'first': out[0], 'last': out[-1]}))
