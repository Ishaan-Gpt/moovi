// node packages/library/scripts/gen-props.mjs: read MotionEasy's style1-props.ts (the renderer's Style 1 prop drawers)
// and write src/style-1/props.ts, the catalog the planner picks from: each draw kind, its one-line description and
// the `p` params it reads. Re-run after MotionEasy adds a prop.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const here = import.meta.dirname, repo = resolve(here, '..', '..', '..');
let d = repo; while (!existsSync(join(d, '..', 'MotionEasy', 'styles')) && dirname(d) !== d) d = dirname(d);
const src = readFileSync(join(process.env.MOTIONEASY_DIR ?? join(d, '..', 'MotionEasy'), 'packages/library/src/style1-props.ts'), 'utf8');
const parts = src.split(/\n\s*case "/).slice(1);
const out = parts.map(part => {
  const kind = part.slice(0, part.indexOf('"'));
  const first = part.split('\n')[0];
  const note = (first.match(/\/\/\s*(.*)$/) ?? [, ''])[1].trim();
  const params = [...new Set([...part.matchAll(/\bP\.([A-Za-z_]\w*)/g)].map(m => m[1]))];
  return { kind, note, params };
});
const body = `// Generated by scripts/gen-props.mjs from MotionEasy packages/library/src/style1-props.ts. Do not hand-edit the list;
// re-run the script. A prop is an image layer {kind: "image", draw: <kind>, cx, cy, w, h, p: {...params}}.

export interface PropKind { kind: string; note: string; params: readonly string[] }

export const PROPS: readonly PropKind[] = ${JSON.stringify(out, null, 1)};

export const PROP_KINDS = PROPS.map(p => p.kind);
`;
writeFileSync(join(here, '..', 'src', 'style-1', 'props.ts'), body);
console.log(`${out.length} props → src/style-1/props.ts`);
